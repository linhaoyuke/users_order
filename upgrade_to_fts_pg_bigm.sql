-- =====================================================================
--  PostgreSQL 使用 pg_bigm 加速 LIKE/ILIKE 查询脚本 (Linux 迁移版)
-- =====================================================================
--
--  说明:
--  1. 此脚本旨在为 `users` 表的文本列创建 bigram 索引，以极大地加速模糊搜索性能，特别是在处理中文等亚洲语言时。
--  2. `pg_bigm` 是一个 PostgreSQL 扩展，需要您在 Linux 服务器上先行安装。
--  3. 此方案适用于已经安装了 `pg_bigm` 扩展的 PostgreSQL 环境。
--
-- =====================================================================

-- 步骤 1: 激活 pg_bigm 扩展
-- 说明: 如果已激活，此命令不会报错。请确保您已在数据库服务器上正确安装了 pg_bigm。
CREATE EXTENSION IF NOT EXISTS pg_bigm;


-- 步骤 2: 为需要搜索的列创建 GIN 索引
-- 说明: 我们将为 username, full_name, 和 email 三个列创建一个统一的 GIN 索引。
--       GIN 索引对于 bigram 的查询性能通常是最好的。
-- 注意: 创建索引可能需要一些时间，具体取决于 `users` 表的大小。
CREATE INDEX IF NOT EXISTS idx_users_bigm ON public.users USING GIN (username gin_bigm_ops, full_name gin_bigm_ops, email gin_bigm_ops);


-- =====================================================================
--  脚本结束
-- =====================================================================
