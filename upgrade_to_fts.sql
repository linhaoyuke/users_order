
-- =====================================================================
--  PostgreSQL 使用 pg_trgm 加速 LIKE/ILIKE 查询脚本
-- =====================================================================
-- 
--  说明:
--  1. 此脚本旨在为 `users` 表的文本列创建 trigram 索引，以极大地加速模糊搜索性能。
--  2. `pg_trgm` 是 PostgreSQL 官方提供的扩展，在 Windows 上通常已内置，无需下载外部文件。
--  3. 此方案是目前在 Windows 环境下最简单、最可靠的高性能搜索优化方案。
--
-- =====================================================================

-- 步骤 1: 激活 pg_trgm 扩展
-- 说明: 如果已激活，此命令不会报错。这步失败的概率极低。
CREATE EXTENSION IF NOT EXISTS pg_trgm;


-- 步骤 2: 为需要搜索的列创建 GIN 索引
-- 说明: 我们将为 username, full_name, 和 email 三个列创建一个统一的 GIN 索引。
--       GIN 索引对于 trigram 的查询性能通常是最好的。
-- 注意: 创建索引可能需要一些时间，具体取决于 `users` 表的大小。
CREATE INDEX IF NOT EXISTS idx_users_trgm ON public.users USING GIN (username gin_trgm_ops, full_name gin_trgm_ops, email gin_trgm_ops);


